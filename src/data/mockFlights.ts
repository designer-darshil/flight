// Helper to generate dynamic flight list for arbitrary airport searches
export function generateAerivaFlights(
  from: Airport,
  to: Airport,
  date: string,
  cabinClass: CabinClass = 'Economy'
): Flight[] {
  // If user searched DEL -> LHR, return the handcrafted flagship flights!
  if (from.code === 'DEL' && to.code === 'LHR') {
    return FLAGSHIP_FLIGHTS.map(f => ({
      ...f,
      departureDate: date,
      cabinClass,
    }));
  }

  const distance = calculateDistance(from.lat, from.lng, to.lat, to.lng);
  const baseMinutes = Math.max(75, Math.round((distance / 820) * 60 + 35));
  let basePrice = Math.max(5200, Math.round(distance * 6.2));
  if (cabinClass === 'Premium Economy') basePrice = Math.round(basePrice * 1.55);
  if (cabinClass === 'Business') basePrice = Math.round(basePrice * 3.2);
  if (cabinClass === 'First') basePrice = Math.round(basePrice * 5.8);

  const carriers = [
    {
      airline: 'Emirates',
      airlineCode: 'EK',
      logoText: 'EK',
      accentColor: '#D71921',
      flightNum: '513',
      aircraft: 'Boeing 777-300ER',
      depHour: 2,
      depMin: 45,
      stops: 1,
      via: 'DXB',
      factor: 1.0,
      tags: ['Best Value', 'Recommended'],
      rec: true,
    },
    {
      airline: 'British Airways',
      airlineCode: 'BA',
      logoText: 'BA',
      accentColor: '#075AAA',
      flightNum: '142',
      aircraft: 'Boeing 787-9 Dreamliner',
      depHour: 3,
      depMin: 20,
      stops: 0,
      via: '',
      factor: 1.18,
      tags: ['Fastest', 'Non-stop'],
      rec: false,
    },
    {
      airline: 'Air India',
      airlineCode: 'AI',
      logoText: 'AI',
      accentColor: '#E31837',
      flightNum: '161',
      aircraft: 'Airbus A350-900',
      depHour: 2,
      depMin: 15,
      stops: 0,
      via: '',
      factor: 0.98,
      tags: ['Extra Baggage', 'Non-stop'],
      rec: false,
    },
    {
      airline: 'Qatar Airways',
      airlineCode: 'QR',
      logoText: 'QR',
      accentColor: '#5C0632',
      flightNum: '571',
      aircraft: 'Airbus A350-1000',
      depHour: 9,
      depMin: 55,
      stops: 1,
      via: 'DOH',
      factor: 1.08,
      tags: ['Skytrax 5-Star'],
      rec: false,
    },
    {
      airline: 'Turkish Airlines',
      airlineCode: 'TK',
      logoText: 'TK',
      accentColor: '#C8102E',
      flightNum: '717',
      aircraft: 'Boeing 787-9',
      depHour: 6,
      depMin: 10,
      stops: 1,
      via: 'IST',
      factor: 0.92,
      tags: ['Cheapest'],
      rec: false,
    },
    {
      airline: 'Lufthansa',
      airlineCode: 'LH',
      logoText: 'LH',
      accentColor: '#05164D',
      flightNum: '761',
      aircraft: 'Boeing 747-8',
      depHour: 1,
      depMin: 45,
      stops: 1,
      via: 'FRA',
      factor: 1.12,
      tags: ['Flagship Fleet'],
      rec: false,
    },
  ];

  return carriers.map((c, idx) => {
    const durMins = c.stops === 0 ? baseMinutes : Math.round(baseMinutes * 1.35);
    const durH = Math.floor(durMins / 60);
    const durM = durMins % 60;
    const durStr = `${durH}h ${durM > 0 ? durM + 'm' : '00m'}`;

    const depH = String(c.depHour).padStart(2, '0');
    const depM = String(c.depMin).padStart(2, '0');
    const depTime = `${depH}:${depM}`;

    const totalDep = c.depHour * 60 + c.depMin;
    const totalArr = totalDep + durMins;
    const arrH = String(Math.floor((totalArr / 60) % 24)).padStart(2, '0');
    const arrM = String(totalArr % 60).padStart(2, '0');
    const arrTime = `${arrH}:${arrM}`;

    const routeStops = c.stops === 0 ? [from.code, to.code] : [from.code, c.via, to.code];
    const price = Math.round(basePrice * c.factor);

    return {
      id: `fl-gen-${c.airlineCode}-${idx}`,
      airline: c.airline,
      airlineCode: c.airlineCode,
      logoText: c.logoText,
      accentColor: c.accentColor,
      flightNumber: `${c.airlineCode} ${c.flightNum}`,
      aircraft: c.aircraft,
      from,
      to,
      departureTime: depTime,
      arrivalTime: arrTime,
      departureDate: date,
      arrivalDate: date,
      duration: durStr,
      durationMinutes: durMins,
      stops: c.stops,
      stopDetails: c.stops === 0 ? 'Non-stop Direct Flight' : `1 Stop via ${c.via}`,
      routeStops,
      priceINR: price,
      cabinClass,
      baggage: {
        cabin: '7 KG',
        checked: '23 KG',
      },
      refundable: idx % 2 === 0,
      refundPolicyText: idx % 2 === 0 ? 'Partial refund upon cancellation' : 'Non-refundable basic fare',
      changePolicyText: 'Date change permitted with fare difference',
      seatsRemaining: Math.floor(Math.random() * 6) + 2,
      co2EmissionsKg: Math.round(distance * 0.11),
      amenities: {
        wifi: true,
        wifiText: 'High-speed Wi-Fi available',
        power: true,
        meal: true,
        mealText: 'Complimentary dining & refreshments',
        entertainment: true,
        legroomInches: 33,
      },
      tags: c.tags,
      recommended: c.rec,
    };
  });
}
